#!/usr/bin/env python3
"""Vendor KaTeX into the Quick Look extension's resources.

Downloads a pinned KaTeX release, checks its SHA-256, and writes
  Core/Sources/MDBuddyCore/Resources/katex.min.js   as shipped
  Core/Sources/MDBuddyCore/Resources/katex.min.css  with every font inlined as a data: URI
Previews have no network or file access for their own assets, so the fonts must live in the
stylesheet. Only the woff2 fonts are kept (WebKit supports them).

Usage: scripts/vendor_katex.py
To update: change VERSION, run once to read the new checksum from the error, set SHA256.
"""
import base64
import hashlib
import io
import re
import tarfile
import urllib.request
from pathlib import Path

VERSION = "0.19.1"
SHA256 = "751e29ffb0c5bc184f08692a0aa905ff86a59ced07f635a27e72a7b7bc53036c"
URL = f"https://github.com/KaTeX/KaTeX/releases/download/v{VERSION}/katex.tar.gz"
RESOURCES = Path(__file__).resolve().parent.parent / "Core" / "Sources" / "MDBuddyCore" / "Resources"


def main() -> None:
    archive = urllib.request.urlopen(URL).read()
    digest = hashlib.sha256(archive).hexdigest()
    if digest != SHA256:
        raise SystemExit(f"checksum mismatch for {URL}\n  expected {SHA256}\n  got      {digest}")

    files = {}
    with tarfile.open(fileobj=io.BytesIO(archive), mode="r:gz") as tar:
        for member in tar.getmembers():
            name = member.name
            if name in ("katex/katex.min.js", "katex/katex.min.css") or re.fullmatch(r"katex/fonts/[\w-]+\.woff2", name):
                files[name] = tar.extractfile(member).read()

    css = files["katex/katex.min.css"].decode("utf-8")

    def inline_fonts(match: re.Match) -> str:
        woff2 = re.search(r"url\((fonts/[\w-]+\.woff2)\)", match.group(0))
        if not woff2:
            raise SystemExit(f"no woff2 source in: {match.group(0)}")
        data = base64.b64encode(files["katex/" + woff2.group(1)]).decode("ascii")
        return f'src:url(data:font/woff2;base64,{data}) format("woff2")'

    css, count = re.subn(r"src:url\([^;}]*", inline_fonts, css)
    if count == 0 or "url(fonts/" in css:
        raise SystemExit("font sources were not all inlined; KaTeX's stylesheet layout has changed")

    header = f"/* KaTeX {VERSION} (MIT). Generated by scripts/vendor_katex.py; do not edit. */\n"
    (RESOURCES / "katex.min.js").write_bytes(header.encode() + files["katex/katex.min.js"])
    (RESOURCES / "katex.min.css").write_text(header + css, encoding="utf-8")
    for name in ("katex.min.js", "katex.min.css"):
        print(f"{name}: {(RESOURCES / name).stat().st_size / 1024:.0f} KB")
    print(f"fonts inlined: {count}")


if __name__ == "__main__":
    main()
